// Minimal in-memory ZIP (STORE, no compression) for the homepage demo's sample download.
// WebP is already compressed, so storing keeps the bytes intact and the code tiny.
export interface ZipEntry { name: string; bytes: Uint8Array }

const crcTable = Uint32Array.from({ length: 256 }, (_, index) => {
  let value = index
  for (let bit = 0; bit < 8; bit++) value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1
  return value >>> 0
})

export function crc32(bytes: Uint8Array): number {
  let crc = 0xffffffff
  for (const byte of bytes) crc = crcTable[(crc ^ byte) & 0xff]! ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}

// Fixed DOS date (2026-11-23 00:00) so identical selections produce identical archives.
const DOS_DATE = ((2026 - 1980) << 9) | (11 << 5) | 23

export function createStoredZipBytes(entries: readonly ZipEntry[]): Uint8Array<ArrayBuffer> {
  if (!entries.length) throw new Error('ZIP cần ít nhất một tệp')
  const encoder = new TextEncoder()
  const parts: Uint8Array[] = []
  const central: Uint8Array[] = []
  let offset = 0

  for (const entry of entries) {
    const name = encoder.encode(entry.name)
    const crc = crc32(entry.bytes)
    const size = entry.bytes.length
    const local = new Uint8Array(30 + name.length)
    const lv = new DataView(local.buffer)
    lv.setUint32(0, 0x04034b50, true)
    lv.setUint16(4, 20, true)
    lv.setUint16(6, 0x0800, true) // UTF-8 names
    lv.setUint16(12, DOS_DATE, true)
    lv.setUint32(14, crc, true)
    lv.setUint32(18, size, true)
    lv.setUint32(22, size, true)
    lv.setUint16(26, name.length, true)
    local.set(name, 30)
    parts.push(local, entry.bytes)

    const record = new Uint8Array(46 + name.length)
    const cv = new DataView(record.buffer)
    cv.setUint32(0, 0x02014b50, true)
    cv.setUint16(4, 20, true)
    cv.setUint16(6, 20, true)
    cv.setUint16(8, 0x0800, true)
    cv.setUint16(14, DOS_DATE, true)
    cv.setUint32(16, crc, true)
    cv.setUint32(20, size, true)
    cv.setUint32(24, size, true)
    cv.setUint16(28, name.length, true)
    cv.setUint32(42, offset, true)
    record.set(name, 46)
    central.push(record)
    offset += local.length + size
  }

  const centralSize = central.reduce((sum, record) => sum + record.length, 0)
  const end = new Uint8Array(22)
  const ev = new DataView(end.buffer)
  ev.setUint32(0, 0x06054b50, true)
  ev.setUint16(8, entries.length, true)
  ev.setUint16(10, entries.length, true)
  ev.setUint32(12, centralSize, true)
  ev.setUint32(16, offset, true)

  const all = [...parts, ...central, end]
  const result = new Uint8Array(all.reduce((sum, part) => sum + part.length, 0))
  let cursor = 0
  for (const part of all) { result.set(part, cursor); cursor += part.length }
  return result
}
